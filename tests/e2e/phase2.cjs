const { chromium } = require('playwright')
const BASE = process.env.KX_BASE || 'http://127.0.0.1:4173/Kutubxona/'
const out = __dirname + '/shots/'
let pass = 0, fail = 0
const ok = (name, cond, extra = '') => { cond ? pass++ : fail++; console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '  ' + extra)) }
const num = (s) => Number((s.match(/[\d ]+/g) || [''])[0].replace(/\s/g, ''))
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } })
  await ctx.addInitScript(() => { try { sessionStorage.setItem('kx:intro-seen', '1') } catch {} })
  const p = await ctx.newPage()
  const errs = []
  p.on('console', m => m.type() === 'error' && errs.push(m.text()))
  p.on('pageerror', e => errs.push(String(e)))
  const go = async (hash) => { await p.goto(BASE + '#' + hash); await p.reload(); await p.waitForTimeout(250) }
  const titles = async () => (await p.locator('main div.grid article h3').allInnerTexts()).map(s => s.trim())
  const prices = async () => (await p.locator('main div.grid article .font-bold.text-\\[15px\\]').allInnerTexts()).map(num)

  // ---- SEARCH
  await go('/search')
  const all = (await titles()).length
  ok('catalog shows all 18 books', all === 18, all)
  ok('placeholder text', (await p.locator('input[type=search]').getAttribute('placeholder')) === "Kitob nomi, muallif yoki mavzu bo'yicha qidiring...")
  const q = async (text) => { await go('/search?q=' + encodeURIComponent(text)); return titles() }
  let t = await q("o'tkan"); ok("title 'o'tkan'", t.includes("O'tkan kunlar"), t)
  t = await q('otkan'); ok("title without apostrophe 'otkan'", t.includes("O'tkan kunlar"), t)
  t = await q('Qodiriy'); ok('author Qodiriy = 2', t.length === 2, t)
  t = await q('fizika'); ok('subject fizika', t.includes('Vaqtning qisqacha tarixi'), t)
  t = await q('kosmos'); ok('subject/title kosmos >= 2', t.includes('Kosmos') && t.includes('Vaqtning qisqacha tarixi'), t)
  t = await q('roman'); ok('genre roman', t.length >= 4, t)
  t = await q('Ilm-fan'); ok('category text Ilm-fan', t.includes('Sapiens') && t.includes('Kosmos'), t)
  t = await q('alkimiyogar'); ok('typo tolerance', t.includes('Alkimyogar'), t)
  t = await q('qodiriy tarix'); ok('multi-word AND', t.length === 2, t)
  t = await q('zzzqq'); ok('no results empty state', t.length === 0 && (await p.locator('text=Hech narsa topilmadi').count()) === 1)
  ok('empty state has recommendations', (await p.locator('text=SHUNGA O\'XSHASH KITOBLAR').count()) === 1)
  await p.getByRole('button', { name: 'Filtrlarni tozalash' }).click(); await p.waitForTimeout(200)
  ok('clear filters restores catalog', (await titles()).length === 18)

  // typing + suggestions (instant)
  await go('/search')
  await p.locator('input[type=search]').click()
  await p.keyboard.type('qod', { delay: 40 })
  ok('suggestions appear while typing', (await p.locator('[role=listbox] li').count()) > 0)
  ok('results filter instantly', (await titles()).length >= 1 && (await titles()).length < 18)
  await p.locator('[role=listbox] li').first().click(); await p.waitForTimeout(200)
  ok('suggestion click applies', (await titles()).length >= 1)
  ok('typed text kept in box', (await p.locator('input[type=search]').inputValue()).length > 0)
  await p.getByRole('button', { name: 'Qidiruvni tozalash' }).click(); await p.waitForTimeout(200)
  ok('clear button resets', (await titles()).length === 18)

  // category chips
  await go('/search')
  await p.getByRole('button', { name: 'Bolalar kitoblari', exact: true }).click(); await p.waitForTimeout(200)
  t = await titles(); ok('category chip filters (3 children books)', t.length === 3, t)
  ok('category in URL', p.url().includes('category='))
  await p.reload(); await p.waitForTimeout(250); ok('category survives refresh', (await titles()).length === 3)

  // filters + sort
  await go('/search')
  await p.getByRole('button', { name: /Filtrlar/ }).click()
  await p.getByLabel('Faqat sotuvda borlari').click(); await p.waitForTimeout(200)
  t = await titles(); ok('in-stock filter hides Noldan birga', !t.includes('Noldan birga') && t.length === 17, t)
  await p.getByLabel('Faqat sotuvda borlari').click(); await p.waitForTimeout(200)
  await p.getByLabel('Faqat chegirmadagilar').click(); await p.waitForTimeout(200)
  t = await titles(); ok('sale filter', t.length === 6, t.length)
  ok('sale cards show discount badge', (await p.locator('main div.grid article >> text=/^−\\d+%$/').count()) === t.length)
  await p.getByLabel('Faqat chegirmadagilar').click(); await p.waitForTimeout(200)
  await p.getByLabel('Narx', { exact: true }).selectOption('0-50000'); await p.waitForTimeout(200)
  let pr = await prices(); ok('price band < 50 000', pr.length > 0 && pr.every(x => x < 50000), pr)
  await p.getByLabel('Narx', { exact: true }).selectOption('80000-'); await p.waitForTimeout(200)
  pr = await prices(); ok('price band >= 80 000', pr.length > 0 && pr.every(x => x >= 80000), pr)
  await p.getByLabel('Narx', { exact: true }).selectOption('')
  await p.getByLabel('Saralash', { exact: true }).selectOption('price-asc'); await p.waitForTimeout(200)
  pr = await prices(); ok('sort price ascending', pr.length === 18 && pr.every((x, i) => i === 0 || pr[i - 1] <= x), pr)
  await p.getByLabel('Saralash', { exact: true }).selectOption('price-desc'); await p.waitForTimeout(200)
  pr = await prices(); ok('sort price descending', pr.every((x, i) => i === 0 || pr[i - 1] >= x), pr)
  await p.getByLabel('Saralash', { exact: true }).selectOption('title'); await p.waitForTimeout(200)
  t = await titles(); ok('sort by title A-Z', t[0] === '1984', t[0])
  await go('/search?flag=bestseller'); t = await titles(); ok('home "Hammasi" flag link works (bestseller)', t.length >= 4 && (await p.locator('h1').innerText()) === 'Bestsellerlar', t.length)
  await go('/search?flag=sale'); ok('flag=sale', (await titles()).length === 6)
  await go('/search?q=sapiens&stock=1'); ok('recommendations under filtered results', (await p.locator("text=SHUNGA O'XSHASH KITOBLAR").count()) === 1)

  // ---- BOOK DETAIL
  await go('/book/otkan-kunlar')
  ok('detail title', (await p.locator('h1').innerText()) === "O'tkan kunlar")
  for (const s of ['Abdulla Qodiriy', 'Badiiy adabiyot', 'Janr', 'Sahifalar', 'Sotuvda bor', '62 000']) ok('detail shows ' + s, (await p.locator('main').innerText()).includes(s))
  ok('detail recs heading', (await p.locator("h2:has-text(\"SHUNGA O'XSHASH KITOBLAR\")").count()) === 1)
  const recT = (await p.locator('main .rail article h3').allInnerTexts()).map(x => x.trim()); ok('recs exclude itself & include Mehrobdan chayon', !recT.includes("O'tkan kunlar") && recT.includes('Mehrobdan chayon'), recT)
  await p.getByRole('link', { name: 'Abdulla Qodiriy', exact: true }).click(); await p.waitForTimeout(250)
  ok('author link searches', (await titles()).length === 2)
  await go('/book/yoq-kitob'); ok('unknown book -> friendly page', (await p.locator('text=Kitob topilmadi').count()) === 1)
  await p.goto(BASE + '#/book/kosmos'); await p.reload(); await p.waitForTimeout(250)
  await p.getByRole('button', { name: /Orqaga/ }).click(); await p.waitForTimeout(250)
  ok('back from direct-open detail goes to catalog', p.url().endsWith('#/search'), p.url())
  // stock cap (Vaqtning qisqacha tarixi: 7)
  await go('/book/vaqtning-qisqacha-tarixi')
  await p.getByRole('button', { name: /Savatga qo‘shish/ }).click()
  for (let i = 0; i < 10; i++) await p.getByRole('button', { name: 'Ko‘paytirish' }).click({ force: true }).catch(() => {})
  ok('qty capped at stock (7)', (await p.locator('[aria-live=polite]').first().innerText()) === '7')
  ok('plus disabled at max', await p.getByRole('button', { name: 'Ko‘paytirish' }).isDisabled())
  // sold-out book
  await go('/book/noldan-birga')
  ok('sold-out button disabled', await p.getByRole('button', { name: /Savatga qo‘shish/ }).isDisabled())

  // ---- CART
  await p.evaluate(() => localStorage.clear())
  await go('/cart')
  ok('empty cart state', (await p.locator('text=Savat bo‘sh').count()) === 1)
  ok('empty cart recs', (await p.locator("h2:has-text(\"SHUNGA O'XSHASH KITOBLAR\")").count()) === 1)
  await go('/')
  await p.getByRole('button', { name: "O'tkan kunlar — savatga qo'shish" }).first().click()
  await p.getByRole('button', { name: "O'tkan kunlar — savatga qo'shish" }).first().click()
  await p.getByRole('button', { name: /Atom odatlar — savatga/ }).first().click()
  ok('nav badge counts items (3)', (await p.locator('nav a[href$="/cart"]').innerText()).includes('3'))
  await p.locator('nav a[href$="/cart"]').click(); await p.waitForTimeout(300)
  const rows = p.locator('main ul > li')
  ok('2 cart lines', (await rows.count()) === 2)
  let total = num(await p.getByTestId('cart-total').innerText())
  ok('total = 2×62 000 + 69 000 = 193 000', total === 193000, total)
  await p.getByRole('button', { name: 'Ko‘paytirish' }).first().click(); await p.waitForTimeout(150)
  total = num(await p.getByTestId('cart-total').innerText()); ok('qty + updates total (255 000)', total === 255000, total)
  await p.getByRole('button', { name: 'Kamaytirish' }).first().click(); await p.getByRole('button', { name: 'Kamaytirish' }).first().click(); await p.waitForTimeout(150)
  total = num(await p.getByTestId('cart-total').innerText()); ok('qty − updates total (131 000)', total === 131000, total)
  ok('recs in cart', (await p.locator("h2:has-text(\"SHUNGA O'XSHASH KITOBLAR\")").count()) === 1)
  await p.reload(); await p.waitForTimeout(250)
  ok('cart persists after refresh', num(await p.getByTestId('cart-total').innerText()) === 131000)
  await p.getByRole('button', { name: /Atom odatlar — savatdan/ }).click(); await p.waitForTimeout(200)
  ok('remove line', (await rows.count()) === 1 && num(await p.getByTestId('cart-total').innerText()) === 62000)
  await p.getByRole('link', { name: 'Xaridni davom ettirish' }).click(); await p.waitForTimeout(200); ok('continue shopping -> catalog', p.url().endsWith('#/search'))
  await p.goBack(); await p.waitForTimeout(200)
  await p.getByRole('link', { name: /Tez buyurtmaga/ }).click(); await p.waitForTimeout(200); ok('proceed -> /order', p.url().endsWith('#/order'))
  await p.goBack(); await p.waitForTimeout(200)
  await p.getByRole('button', { name: 'Savatni tozalash' }).click(); await p.waitForTimeout(200)
  ok('clear cart -> empty', (await p.locator('text=Savat bo‘sh').count()) === 1)
  // stationery in cart
  await go('/')
  await p.getByRole('button', { name: /Daftar, 96 varaq.*savatga/ }).click(); await p.waitForTimeout(150)
  await p.locator('nav a[href$="/cart"]').click(); await p.waitForTimeout(250)
  ok('stationery line renders & totals', num(await p.getByTestId('cart-total').innerText()) === 14000)

  // ---- FAVORITES
  await p.evaluate(() => localStorage.clear())
  await go('/favorites')
  ok('empty favorites state', (await p.locator('text=Sevimlilar hozircha bo‘sh').count()) === 1)
  await go('/')
  await p.getByRole('button', { name: "Sevimlilarga qo'shish" }).nth(0).click()
  await p.getByRole('button', { name: "Sevimlilarga qo'shish" }).nth(0).click()
  ok('home heart badge shows 2', (await p.locator('header a[href$="/favorites"]').innerText()).includes('2'))
  await p.locator('header a[href$="/favorites"]').click(); await p.waitForTimeout(300)
  ok('favorites page lists 2', (await titles()).length >= 2 && (await p.locator('h1').innerText()).includes('(2)'))
  ok('favorites recs', (await p.locator("h2:has-text(\"SHUNGA O'XSHASH KITOBLAR\")").count()) === 1)
  await p.reload(); await p.waitForTimeout(250); ok('favorites persist after refresh', (await p.locator('h1').innerText()).includes('(2)'))
  await p.getByRole('button', { name: 'Hammasini savatga' }).click(); await p.waitForTimeout(200)
  ok('add all to cart badge', (await p.locator('nav a[href$="/cart"]').innerText()).includes('2'))
  await p.getByRole('button', { name: 'Sevimlilardan olib tashlash' }).first().click(); await p.waitForTimeout(200)
  ok('remove favorite', (await p.locator('h1').innerText()).includes('(1)'))
  await go('/'); ok('home personalised recs after favorite/cart', (await p.locator("h2:has-text(\"SHUNGA O'XSHASH KITOBLAR\")").count()) === 1)
  await p.screenshot({ path: out + 'p2-home.png' })

  // ---- Refresh on every route + nav
  for (const r of ['/', '/search', '/search?q=sapiens', '/cart', '/favorites', '/order', '/account', '/book/sapiens', '/stationery', '/print', '/admin']) {
    await go(r); ok('refresh ' + r + ' renders', (await p.locator('main').innerText()).trim().length > 20)
  }
  await go('/') // /admin intentionally has no customer bottom nav (Phase 4)
  for (const [label, hash] of [['Qidiruv', '/search'], ['Savat', '/cart'], ['Tez buyurtma', '/order'], ['Hisob', '/account'], ['Bosh sahifa', '/']]) {
    await p.locator('nav').getByText(label, { exact: true }).click(); await p.waitForTimeout(250)
    ok('bottom nav → ' + label, p.url().endsWith('#' + hash), p.url())
  }
  await p.goto(BASE + '#/account?tab=favorites'); await p.reload(); await p.waitForTimeout(250)
  await p.getByRole('link', { name: /Barcha sevimlilar/ }).click(); await p.waitForTimeout(200); ok('account → favorites link', p.url().endsWith('#/favorites'))

  // ---- screenshots
  await go('/search?q=qodiriy'); await p.screenshot({ path: out + 'p2-search.png' })
  await p.getByRole('button', { name: /Filtrlar/ }).click(); await p.waitForTimeout(400); await p.screenshot({ path: out + 'p2-search-filters.png' })
  await go('/book/otkan-kunlar'); await p.screenshot({ path: out + 'p2-detail.png' }); await p.screenshot({ path: out + 'p2-detail-full.png', fullPage: true })
  await go('/'); await p.getByRole('button', { name: /savatga qo'shish/ }).nth(2).click(); await p.getByRole('button', { name: /savatga qo'shish/ }).nth(3).click()
  await go('/cart'); await p.screenshot({ path: out + 'p2-cart.png' })
  await go('/favorites'); await p.screenshot({ path: out + 'p2-fav.png' })
  // desktop
  const d = await (await b.newContext({ viewport: { width: 1280, height: 800 } })).newPage()
  await d.addInitScript(() => sessionStorage.setItem('kx:intro-seen', '1'))
  d.on('pageerror', e => errs.push(String(e)))
  await d.goto(BASE + '#/search'); await d.waitForTimeout(400); await d.screenshot({ path: out + 'p2-search-desktop.png' })
  await d.goto(BASE + '#/book/kosmos'); await d.waitForTimeout(400); await d.screenshot({ path: out + 'p2-detail-desktop.png' })
  // intro still plays on a fresh session
  const f = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage()
  await f.goto(BASE); await f.waitForTimeout(400)
  ok('Phase 1 intro still plays on first visit', (await f.locator('text=O‘tkazib yuborish').count()) === 1)
  await f.waitForTimeout(2300); ok('intro ends, homepage visible', (await f.locator('text=Bugun nima o‘qiymiz?').count()) === 1)

  ok('no console/page errors', errs.length === 0, JSON.stringify(errs))
  console.log(`\n${pass} passed, ${fail} failed`)
  await b.close()
})()
